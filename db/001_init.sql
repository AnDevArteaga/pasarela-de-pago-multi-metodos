CREATE TABLE IF NOT EXISTS schema_migrations (
  id text PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS origins (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  signing_secret text NOT NULL,
  notify_secret text NOT NULL,
  mail_from text NOT NULL,
  active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  origin_id integer NOT NULL REFERENCES origins(id),
  name text NOT NULL,
  description text NOT NULL DEFAULT '',
  price_cents bigint NOT NULL,
  type text NOT NULL,
  active boolean NOT NULL DEFAULT true,
  notify_url text NULL,
  notify_kind text NOT NULL,
  origin_reference text NULL,
  billing_interval text NOT NULL DEFAULT 'month',
  interval_count integer NOT NULL DEFAULT 1,
  max_attempts integer NOT NULL DEFAULT 3,
  retry_days text NOT NULL DEFAULT '1,3,5',
  grace_days integer NOT NULL DEFAULT 3,
  CONSTRAINT products_type_chk CHECK (type IN ('one_time', 'subscription')),
  CONSTRAINT products_kind_chk CHECK (notify_kind IN ('one_time', 'subscription')),
  CONSTRAINT products_kind_matches_chk CHECK (notify_kind = type),
  CONSTRAINT products_interval_chk CHECK (billing_interval IN ('month', 'year'))
);

CREATE TABLE IF NOT EXISTS checkout_sessions (
  id uuid PRIMARY KEY,
  product_id integer NOT NULL REFERENCES products(id),
  ref text NULL,
  origin_id integer NOT NULL REFERENCES origins(id),
  signed boolean NOT NULL DEFAULT false,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS acceptances (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  checkout_session_id uuid NULL,
  payment_id uuid NULL,
  kind text NOT NULL,
  text_version text NOT NULL,
  accepted_at timestamptz NOT NULL,
  ip text NOT NULL
);

CREATE TABLE IF NOT EXISTS payment_sources (
  id uuid PRIMARY KEY,
  origin_id integer NOT NULL REFERENCES origins(id),
  ref text NOT NULL,
  wompi_source_id text NOT NULL,
  type text NOT NULL,
  brand text NULL,
  last_four text NULL,
  status text NOT NULL,
  customer_email text NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS payment_sources_origin_ref_wompi_uidx
  ON payment_sources (origin_id, ref, wompi_source_id);

CREATE TABLE IF NOT EXISTS subscriptions (
  id uuid PRIMARY KEY,
  origin_id integer NOT NULL REFERENCES origins(id),
  ref text NOT NULL,
  product_id integer NOT NULL REFERENCES products(id),
  payment_source_id uuid NULL REFERENCES payment_sources(id),
  status text NOT NULL,
  price_cents bigint NOT NULL,
  currency text NOT NULL DEFAULT 'COP',
  current_period_start timestamptz NULL,
  current_period_end timestamptz NULL,
  next_billing_at timestamptz NULL,
  attempt_count integer NOT NULL DEFAULT 0,
  next_retry_at timestamptz NULL,
  cancel_at_period_end boolean NOT NULL DEFAULT false,
  canceled_at timestamptz NULL,
  cancel_reason text NULL,
  access_end_notified boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT subscriptions_status_chk CHECK (
    status IN ('incomplete', 'active', 'past_due', 'suspended', 'canceled', 'expired')
  )
);

CREATE INDEX IF NOT EXISTS subscriptions_billing_idx
  ON subscriptions (status, next_billing_at);

CREATE TABLE IF NOT EXISTS payments (
  id uuid PRIMARY KEY,
  public_id uuid NOT NULL UNIQUE,
  origin_id integer NOT NULL REFERENCES origins(id),
  product_id integer NOT NULL REFERENCES products(id),
  subscription_id uuid NULL REFERENCES subscriptions(id),
  ref text NULL,
  amount_cents bigint NOT NULL,
  method text NOT NULL,
  wompi_transaction_id text NULL,
  wompi_reference text NOT NULL,
  status text NOT NULL,
  status_detail text NULL,
  idempotency_key text NOT NULL UNIQUE,
  attempt_number integer NOT NULL DEFAULT 1,
  period_start date NULL,
  payer_email text NULL,
  payer_name text NULL,
  payer_legal_id text NULL,
  payer_legal_id_type text NULL,
  payer_phone text NULL,
  card_brand text NULL,
  card_last_four text NULL,
  async_payment_url text NULL,
  first_period boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT payments_status_chk CHECK (status IN ('PENDING', 'APPROVED', 'DECLINED', 'ERROR', 'VOIDED'))
);

CREATE UNIQUE INDEX IF NOT EXISTS payments_sub_period_attempt_uidx
  ON payments (subscription_id, period_start, attempt_number)
  WHERE subscription_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS payments_pending_idx ON payments (status, created_at);
CREATE INDEX IF NOT EXISTS payments_wompi_idx ON payments (wompi_transaction_id);

CREATE TABLE IF NOT EXISTS webhook_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_key text NOT NULL UNIQUE,
  payload text NOT NULL,
  received_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS outbox (
  id uuid PRIMARY KEY,
  type text NOT NULL,
  payload text NOT NULL,
  payment_id uuid NULL,
  subscription_id uuid NULL,
  status text NOT NULL,
  attempts integer NOT NULL DEFAULT 0,
  next_attempt_at timestamptz NOT NULL,
  last_error text NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz NULL,
  event_key text NOT NULL,
  CONSTRAINT outbox_type_chk CHECK (type IN ('notify_origin', 'send_email')),
  CONSTRAINT outbox_status_chk CHECK (status IN ('pending', 'sent', 'failed'))
);

CREATE UNIQUE INDEX IF NOT EXISTS outbox_type_event_uidx ON outbox (type, event_key);
CREATE INDEX IF NOT EXISTS outbox_due_idx ON outbox (status, next_attempt_at);
